import { mkdtemp, mkdir, readdir, readFile, rm, symlink, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { GraphStore } from '../src/store/graph.js'
import { atomicJson, exists } from '../src/store/io.js'

const cleanup: string[] = []
afterEach(async () => { for (const dir of cleanup.splice(0)) await rm(dir, { recursive: true, force: true }) })
async function setup(initialize = true) {
  const cwd = await mkdtemp(path.join(os.tmpdir(), 'sapper M1 中文 '))
  cleanup.push(cwd)
  const root = path.join(cwd, '.sapper')
  const store = new GraphStore(root, cwd)
  if (initialize) await store.init('unit test', '验证存储兼容性')
  return { store, root, cwd }
}
const fact = (description = 'observed host') => ({ description, kind: 'host', data: { host: '127.0.0.1', port: 8080, tls: false, empty: null } })

describe('M1 graph persistence', () => {
  it('reads an absent graph without creating any files', async () => {
    const { store, cwd } = await setup(false)
    expect(await store.initialized()).toBe(false)
    await expect(store.read()).rejects.toThrow('尚未初始化')
    expect(await readdir(cwd)).toEqual([])
  })
  it('initializes a terminal goal fact and never overwrites an existing graph', async () => {
    const { store, root } = await setup()
    const before = await readFile(path.join(root, 'project.json'), 'utf8')
    const graph = await store.read()
    expect(graph.project.counters).toEqual({ fact: 0, intent: 0, hint: 0, run: 0 })
    expect(graph.facts).toMatchObject([{ id: 'goal', creator: 'system' }])
    expect(graph.integrity).toEqual([])
    await expect(store.init('different', 'overwrite')).rejects.toThrow('已存在')
    expect(await readFile(path.join(root, 'project.json'), 'utf8')).toBe(before)
    expect(await exists(path.join(root, '.transaction.json'))).toBe(false)
    expect(await exists(path.join(root, 'LOCK'))).toBe(false)
  })
  it('rejects an empty goal and a nonempty destination, preserving original files', async () => {
    const { store, root, cwd } = await setup(false)
    await expect(store.init('', ' ')).rejects.toThrow('不能为空')
    expect(await readdir(cwd)).toEqual([])
    await mkdir(root)
    await writeFile(path.join(root, 'keep.txt'), 'original')
    await expect(store.init('', 'goal')).rejects.toThrow('目录非空')
    expect(await readdir(root)).toEqual(['keep.txt'])
  })
  it('normalizes typed data and skips occupied IDs with stale counters', async () => {
    const { store, root } = await setup()
    const first = await store.addFact({ ...fact(), title: ' host ', doc: ' evidence\r\nline ' }, 'tester')
    expect(first).toMatchObject({ id: 'f001', title: 'host', data: { host: '127.0.0.1', port: '8080', tls: 'false' }, doc: 'evidence\r\nline' })
    const project = (await store.read()).project
    project.counters.fact = 0
    await atomicJson(path.join(root, 'project.json'), project)
    expect((await store.addFact(fact('another'), 'tester')).id).toBe('f002')
    expect((await store.readNode('fact', 'f001')).description).toBe('observed host')
    const raw = await readFile(path.join(root, 'facts/f001.json'), 'utf8')
    expect(raw.endsWith('\n')).toBe(true)
    expect(raw.charCodeAt(0)).not.toBe(0xfeff)
  })
  it('serializes concurrent writers across Store instances without lost IDs', async () => {
    const { root, cwd, store } = await setup()
    const nodes = await Promise.all(Array.from({ length: 24 }, (_, n) => new GraphStore(root, cwd).addFact(fact(`fact ${n}`), 'tester')))
    expect(new Set(nodes.map(n => n.id)).size).toBe(24)
    const graph = await store.read()
    expect(graph.facts).toHaveLength(25)
    expect(graph.project.counters.fact).toBe(24)
    expect(graph.integrity).toEqual([])
  })
  it('refuses unsafe IDs, malformed data and nonexistent dependencies', async () => {
    const { store } = await setup()
    await expect(store.readNode('fact', '../project')).rejects.toThrow('无效')
    await expect(store.addFact({ description: 'x', data: { nested: { value: 1 } } }, 't')).rejects.toThrow('只接受')
    await expect(store.addFact({ description: 'x', data: { 'bad/key': 'v' } }, 't')).rejects.toThrow('字段名')
    await expect(store.addFact({ description: 'x', kind: 'unknown' }, 't')).rejects.toThrow('kind')
    await expect(store.addIntent({ from: ['goal'], description: 'bad' }, 't')).rejects.toThrow('依赖')
    await expect(store.addIntent({ from: ['f404'], description: 'bad' }, 't')).rejects.toThrow('依赖')
    expect((await store.read()).project.counters.fact).toBe(0)
  })
  it('keeps corrupted nodes inspectable and blocks writes without changing them', async () => {
    const { store, root } = await setup()
    const original = await store.addFact(fact(), 'tester')
    const file = path.join(root, 'facts/f001.json')
    await writeFile(file, '{broken')
    const graph = await store.read()
    expect(graph.warnings[0]).toContain('f001.json')
    expect(graph.facts.map(f => f.id)).toEqual(['goal'])
    await expect(store.readNode('fact', 'f001')).rejects.toThrow('无法读取')
    await expect(store.addFact(fact(), 'tester')).rejects.toThrow('写入已停止')
    expect(await readFile(file, 'utf8')).toBe('{broken')
    const invalidUtf8 = Buffer.from(JSON.stringify({ ...original, description: '?' }))
    invalidUtf8[invalidUtf8.indexOf('?')] = 0xff
    await writeFile(file, invalidUtf8)
    expect((await store.read()).warnings[0]).toContain('f001.json')
    expect((await store.read()).facts.map(f => f.id)).toEqual(['goal'])
  })
  it('diagnoses dangling references, missing goal, and malformed project metadata', async () => {
    const { store, root } = await setup()
    const created = await store.addFact(fact(), 'tester')
    await store.addIntent({ from: [created.id], description: 'check' }, 'tester')
    await rm(path.join(root, 'facts/f001.json'))
    await rm(path.join(root, 'facts/goal.json'))
    expect((await store.read()).integrity).toEqual(expect.arrayContaining([expect.stringContaining('goal'), expect.stringContaining('依赖')]))
    await writeFile(path.join(root, 'project.json'), '{"goal":"M0 fixture","status":"active"}')
    await expect(store.read()).rejects.toThrow('M0')
  })
  it('updates only documents and rejects stale document writes', async () => {
    const { store } = await setup()
    const node = await store.addFact({ ...fact(), doc: 'v1' }, 'tester')
    const updates = await Promise.allSettled([
      store.updateDoc(node.id, 'v2', 'v1'), store.updateDoc(node.id, 'v3', 'v1'),
    ])
    expect(updates.filter(r => r.status === 'fulfilled')).toHaveLength(1)
    const changed = await store.readNode('fact', node.id)
    expect(changed.description).toBe(node.description)
    expect(changed.created_at).toBe(node.created_at)
    await expect(store.updateDoc(node.id, null, 'v1')).rejects.toThrow('重新读取')
  })
  it('enforces intent confirmation and claim ownership before creating result facts', async () => {
    const { store } = await setup()
    const seed = await store.addFact(fact(), 'tester')
    const intent = await store.addIntent({ from: [seed.id, seed.id], description: 'inspect', requires_confirmation: true }, 'tester')
    expect(intent.from).toEqual([seed.id])
    await expect(store.intentAction('claim', intent.id, 'a')).rejects.toThrow('confirm')
    await store.intentAction('confirm', intent.id, 'human')
    await store.intentAction('claim', intent.id, 'a')
    await expect(store.addFact({ description: 'evidence', source_intent: intent.id }, 'b')).rejects.toThrow('领取')
    await expect(store.intentAction('release', intent.id, 'b')).rejects.toThrow('领取')
    await store.intentAction('release', intent.id, 'a')
    await store.intentAction('claim', intent.id, 'b')
    expect((await store.addFact({ description: 'evidence', source_intent: intent.id }, 'b')).id).toBe('f002')
    expect((await store.read()).integrity).toEqual([])
  })
  it('concludes a raced intent exactly once without orphan facts', async () => {
    const { store } = await setup()
    const seed = await store.addFact(fact(), 'tester')
    const intent = await store.addIntent({ from: [seed.id], description: 'inspect' }, 'tester')
    const results = await Promise.allSettled(Array.from({ length: 5 }, () => store.addFact({ description: 'result', source_intent: intent.id }, 'tester')))
    expect(results.filter(r => r.status === 'fulfilled')).toHaveLength(1)
    expect((await store.read()).project.counters.fact).toBe(2)
    expect((await store.readNode('intent', intent.id)).to).toBe('f002')
  })
  it('links existing result facts, completes the project, and rejects duplicate completion', async () => {
    const { store } = await setup()
    const seed = await store.addFact(fact(), 'tester')
    const result = await store.addFact(fact('result'), 'tester')
    const intent = await store.addIntent({ from: [seed.id], description: 'inspect' }, 'tester')
    await store.intentAction('conclude', intent.id, 'tester', result.id)
    const done = await store.addIntent({ from: [result.id], description: 'complete' }, 'tester')
    await store.intentAction('conclude', done.id, 'tester', 'goal')
    expect((await store.read()).project.status).toBe('completed')
    expect((await store.read()).integrity).toEqual([])
    await expect(store.intentAction('conclude', done.id, 'tester', 'goal')).rejects.toThrow('已结案')
    const another = await store.addIntent({ from: [result.id], description: 'duplicate' }, 'tester')
    await expect(store.intentAction('conclude', another.id, 'tester', 'goal')).rejects.toThrow('已完成')
  })
  it('records a hint in the Python-compatible layout', async () => {
    const { store } = await setup()
    expect(await store.addHint('  retry with evidence  ', 'tester')).toMatchObject({ id: 'h001', content: 'retry with evidence' })
    expect((await store.read()).hints).toHaveLength(1)
  })
  it('deduplicates normalized flags, preserves case, and changes only explicit lifecycle state', async () => {
    const { store, root } = await setup()
    const source = await store.addFact(fact(), 'tester')
    const first = await store.recordFlag('  ｆｌａｇ{Case}  ', 'tester', { source_fact: source.id })
    expect(first.entry).toMatchObject({ value: 'flag{Case}', status: 'recorded', source_fact: source.id })
    const duplicate = await store.recordFlag('flag{Case}', 'tester')
    expect(duplicate).toMatchObject({ duplicate: true, entry: { id: first.entry.id } })
    const different = await store.recordFlag('flag{case}', 'tester')
    expect(different.duplicate).toBe(false)
    const before = await store.readNode('fact', first.entry.id)
    expect(await store.updateFlag(first.entry.id, 'submitted', 'user confirmed')).toMatchObject({ status: 'submitted', note: 'user confirmed' })
    const after = await store.readNode('fact', first.entry.id)
    expect(after.created_at).toBe(before.created_at)
    expect(after.description).toBe(before.description)
    const ledger = JSON.parse(await readFile(path.join(root, 'flags/ledger.json'), 'utf8'))
    expect(ledger.entries).toHaveLength(2)
    await expect(store.updateFlag(source.id, 'rejected', '')).rejects.toThrow('不是 flag')
  })
  it('rebuilds a missing or corrupt ledger from flag facts without trusting the index', async () => {
    const { store, root } = await setup()
    const old = await store.addFact({ description: 'python flag', kind: 'flag', data: { value: 'flag{old}', status: 'recorded' } }, 'python')
    await store.updateFlag(old.id, 'rejected', undefined)
    await rm(path.join(root, 'flags/ledger.json'))
    expect(store.flagEntries((await store.read()).facts)).toMatchObject([{ value: 'flag{old}', status: 'rejected' }])
    expect(await exists(path.join(root, 'flags/ledger.json'))).toBe(false)
    await writeFile(path.join(root, 'flags/ledger.json'), '{broken')
    expect((await store.recordFlag('flag{old}', 'tester')).duplicate).toBe(true)
    expect(JSON.parse(await readFile(path.join(root, 'flags/ledger.json'), 'utf8')).entries).toHaveLength(1)
  })
  it('refuses external writer locks and does not steal an abandoned lock', async () => {
    const { store, root } = await setup()
    await mkdir(path.join(root, 'LOCK'))
    await expect(store.addFact(fact(), 'tester')).rejects.toThrow('LOCK')
    await expect(store.read()).rejects.toThrow('LOCK')
    expect(await exists(path.join(root, 'LOCK'))).toBe(true)
  })
  it('enforces flag validity and deduplication through generic fact writes too', async () => {
    const { store } = await setup()
    await expect(store.addFact({ description: 'bad flag', kind: 'flag' }, 'tester')).rejects.toThrow('data.value')
    await expect(store.addFact({ description: 'spoofed submission', kind: 'flag', data: { value: 'flag{ONE}', status: 'submitted' } }, 'tester')).rejects.toThrow('必须为 recorded')
    await store.recordFlag('flag{ONE}', 'tester')
    await expect(store.addFact({ description: 'duplicate flag', kind: 'flag', data: { value: 'flag{ONE}' } }, 'tester')).rejects.toThrow('已记录')
    expect((await store.read()).project.counters.fact).toBe(1)
  })
  it('does not commit writes cancelled or rejected by a live configuration guard', async () => {
    const { store } = await setup()
    await expect(store.addFact(fact(), 'tester', { signal: AbortSignal.abort() })).rejects.toThrow()
    await expect(store.addFact(fact(), 'tester', { guard: () => { throw new Error('disabled') } })).rejects.toThrow('disabled')
    expect((await store.read()).project.counters.fact).toBe(0)
  })
  it('preserves a previous destination and cleans temporary files on replacement failure', async () => {
    const { root } = await setup()
    const destination = path.join(root, 'keep')
    await mkdir(destination)
    await writeFile(path.join(destination, 'original'), 'original')
    await expect(atomicJson(destination, { replace: true })).rejects.toThrow()
    expect(await readFile(path.join(destination, 'original'), 'utf8')).toBe('original')
    expect((await readdir(root)).filter(name => name.endsWith('.tmp'))).toEqual([])
  })
  it('refuses symlink/junction paths for the store and node files', async () => {
    const { store, root, cwd } = await setup()
    const outside = path.join(cwd, 'outside')
    await mkdir(outside)
    const other = path.join(cwd, 'linked-store')
    await symlink(outside, other, 'junction')
    await expect(new GraphStore(other, cwd).init('', 'bad')).rejects.toThrow('符号链接')
    await symlink(outside, path.join(root, 'linked'), 'junction')
    const nested = new GraphStore(path.join(root, 'linked', 'graph'), cwd)
    await expect(nested.init('', 'bad')).rejects.toThrow('符号链接')
    expect(await readdir(outside)).toEqual([])
    expect((await store.read()).integrity).toEqual([])
  })
})

describe('transaction recovery', () => {
  it('retains a real failed multi-file commit and recovers without allocating another fact', async () => {
    const { store, root } = await setup()
    await rm(path.join(root, 'meta.json'))
    // A directory at the metadata destination forces the real rename operation to fail.
    await mkdir(path.join(root, 'meta.json'))
    await expect(store.addFact(fact(), 'tester')).rejects.toThrow()
    expect(await exists(path.join(root, 'facts/f001.json'))).toBe(true)
    expect(await exists(path.join(root, '.transaction.json'))).toBe(true)
    await expect(store.read()).rejects.toThrow('未完成事务')
    await rm(path.join(root, 'meta.json'), { recursive: true })
    expect((await store.recover()).project.counters.fact).toBe(1)
    expect((await store.read()).facts).toHaveLength(2)
    expect((await store.addFact(fact(), 'tester')).id).toBe('f002')
  })
  it('blocks readers on a partial commit and replays it idempotently under the writer lock', async () => {
    const { store, root } = await setup()
    const graph = await store.read()
    const value = { id: 'f001', description: 'committed evidence', creator: 'tester', created_at: graph.project.created_at, source_intent: null }
    graph.project.counters.fact = 1
    const entries = [{ file: 'facts/f001.json', value }, { file: 'project.json', value: graph.project }]
    await atomicJson(path.join(root, '.transaction.json'), { version: 1, entries })
    await atomicJson(path.join(root, 'facts/f001.json'), value)
    await expect(store.read()).rejects.toThrow('未完成事务')
    expect((await store.recover()).project.counters.fact).toBe(1)
    expect((await store.recover()).facts).toHaveLength(2)
    expect((await store.addFact(fact(), 'tester')).id).toBe('f002')
    expect(await exists(path.join(root, '.transaction.json'))).toBe(false)
  })
  it('validates the complete journal before replaying anything', async () => {
    const { store, root, cwd } = await setup()
    const before = await readFile(path.join(root, 'project.json'), 'utf8')
    const project = (await store.read()).project
    project.goal = 'must not change'
    await atomicJson(path.join(root, '.transaction.json'), { version: 1, entries: [
      { file: 'project.json', value: project }, { file: '../escape.json', value: {} },
    ] })
    await expect(store.recover()).rejects.toThrow('越界')
    expect(await readFile(path.join(root, 'project.json'), 'utf8')).toBe(before)
    expect(await exists(path.join(cwd, 'escape.json'))).toBe(false)
    expect(await exists(path.join(root, '.transaction.json'))).toBe(true)
  })
})
